// Utility to generate ellipse polygon for origin uncertainty
function generateEllipse(centerLng: number, centerLat: number, radiusKm: number, points = 32): [number, number][] {
  const coords: [number, number][] = [];
  const kmToLng = 1 / (111.32 * Math.cos((centerLat * Math.PI) / 180));
  const kmToLat = 1 / 110.574;

  for (let i = 0; i <= points; i++) {
    const angle = (i * 2 * Math.PI) / points;
    const dx = radiusKm * 1.3 * Math.cos(angle) * kmToLng;
    const dy = radiusKm * 0.8 * Math.sin(angle) * kmToLat;
    coords.push([centerLng + dx, centerLat + dy]);
  }
  return coords;
}

